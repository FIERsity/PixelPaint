function initialLanguage(): Language {
  try {
    return localStorage.getItem("pixelpaint:language") === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

function interpolate(message: string, vars?: Vars): string {
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Vars) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  const t = useCallback((key: string, vars?: Vars) => {
    const message = messages[language][key] ?? messages.zh[key] ?? key;
    return interpolate(message, vars);
  }, [language]);

  useEffect(() => {
    try { localStorage.setItem("pixelpaint:language", language); } catch { /* ignore */ }
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
    document.title = t("pageTitle");
  }, [language, t]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);
  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
